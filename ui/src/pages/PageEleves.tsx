/** cloneme: P-03 — élèves, recherche, filtre et tiroir de profil. */

import { useEffect, useMemo, useRef, useState } from 'react'
import { createPortal } from 'react-dom'
import { useNavigate, useSearchParams } from 'react-router-dom'
import { useDonnees } from '../state/Donnees'
import { useNotifications } from '../state/Notifications'
import { useEchap } from '../hooks/useEchap'
import { usePiegeFocus } from '../hooks/usePiegeFocus'
import { useVerrouDefilement } from '../hooks/useVerrouDefilement'
import type { Eleve } from '../lib/types'
import { Avatar } from '../composants/Avatar'
import { Bouton, LienBouton } from '../composants/Bouton'
import { EntetePage } from '../composants/EntetePage'
import { EtatVide } from '../composants/EtatVide'
import { Icone } from '../composants/Icones'
import { Pastille } from '../composants/Pastille'
import { TableauEleves } from '../composants/TableauEleves'
import { useTitrePage } from '../hooks/useTitrePage'
import './PageEleves.css'

export function PageEleves() {
  useTitrePage('Students')
  const { eleves, groupes, groupeParId, conversations } = useDonnees()
  const { notifier } = useNotifications()
  const navigate = useNavigate()
  const [params, setParams] = useSearchParams()
  const paramEleve = params.get('eleve')

  const [requete, setRequete] = useState('')
  const [filtre, setFiltre] = useState('tous')
  const [selectionId, setSelectionId] = useState<string | null>(paramEleve)
  const panneau = useRef<HTMLElement>(null)

  useEffect(() => {
    setSelectionId(paramEleve)
  }, [paramEleve])

  const selection = selectionId ? eleves.find(eleve => eleve.id === selectionId) : undefined
  useEchap(Boolean(selection), () => fermer())
  useVerrouDefilement(Boolean(selection))
  usePiegeFocus(panneau, Boolean(selection))

  const moyenne = Math.round(eleves.reduce((total, eleve) => total + eleve.assiduite, 0) / eleves.length)
  const attention = eleves.filter(eleve => eleve.assiduite < 80).length

  const resultats = useMemo(
    () =>
      eleves.filter(eleve => {
        const groupe = groupeParId(eleve.groupeId)
        const texte = `${eleve.prenom} ${eleve.nom} ${eleve.email} ${groupe?.code ?? ''}`.toLowerCase()
        const bonneRecherche = !requete.trim() || texte.includes(requete.trim().toLowerCase())
        const bonGroupe = filtre === 'tous' || eleve.groupeId === filtre
        return bonneRecherche && bonGroupe
      }),
    [eleves, filtre, requete, groupeParId],
  )

  function ouvrir(eleve: Eleve) {
    setSelectionId(eleve.id)
    const suivant = new URLSearchParams(params)
    suivant.set('eleve', eleve.id)
    setParams(suivant, { replace: true })
  }

  function fermer() {
    setSelectionId(null)
    if (paramEleve) {
      const suivant = new URLSearchParams(params)
      suivant.delete('eleve')
      setParams(suivant, { replace: true })
    }
  }

  function ecrire(eleve: Eleve) {
    const fil = conversations.find(conversation => conversation.eleveId === eleve.id)
    fermer()
    navigate(fil ? `/messages?fil=${fil.id}` : `/messages?eleve=${eleve.id}`)
  }

  function reinitialiser() {
    setRequete('')
    setFiltre('tous')
  }

  return (
    <section className="panneau-page page-eleves" aria-labelledby="titre-eleves">
      <EntetePage
        surtitre="Your class"
        titre="Students"
        sousTitre="Attendance, recent activity and a direct line to every student."
        actions={
          <Bouton
            variante="fantome"
            onClick={() =>
              notifier({
                titre: 'Export is a demo',
                description: 'A CSV export would be generated by the backend.',
                ton: 'info',
              })
            }
            iconeGauche={<Icone nom="file" taille={16} />}
          >
            Export list
          </Bouton>
        }
      />

      <div className="eleves__stats">
        <div className="stat-eleve">
          <span className="stat-eleve__icone">
            <Icone nom="students" taille={18} />
          </span>
          <div>
            <p className="stat-eleve__valeur">{eleves.length}</p>
            <p className="stat-eleve__libelle">students in this view</p>
          </div>
        </div>
        <div className="stat-eleve">
          <span className="stat-eleve__icone">
            <Icone nom="check" taille={18} />
          </span>
          <div>
            <p className="stat-eleve__valeur">{moyenne}%</p>
            <p className="stat-eleve__libelle">average attendance</p>
          </div>
        </div>
        <div className="stat-eleve">
          <span className="stat-eleve__icone stat-eleve__icone--alerte">
            <Icone nom="alert" taille={18} />
          </span>
          <div>
            <p className="stat-eleve__valeur">{attention}</p>
            <p className="stat-eleve__libelle">need a check-in</p>
          </div>
        </div>
      </div>

      <div className="eleves__barre">
        <div className="recherche-locale">
          <Icone nom="search" taille={18} />
          <input
            value={requete}
            onChange={evenement => setRequete(evenement.target.value)}
            placeholder="Search a name, an email…"
            aria-label="Search students"
          />
          {requete && (
            <button type="button" onClick={() => setRequete('')} aria-label="Clear search">
              <Icone nom="close" taille={14} />
            </button>
          )}
        </div>

        <div className="filtres" role="group" aria-label="Filter by group">
          <button
            type="button"
            className={['filtre', filtre === 'tous' && 'filtre--actif'].filter(Boolean).join(' ')}
            onClick={() => setFiltre('tous')}
            aria-pressed={filtre === 'tous'}
          >
            All groups
          </button>
          {groupes.map(groupe => (
            <button
              key={groupe.id}
              type="button"
              className={['filtre', filtre === groupe.id && 'filtre--actif'].filter(Boolean).join(' ')}
              onClick={() => setFiltre(groupe.id)}
              aria-pressed={filtre === groupe.id}
            >
              {groupe.code}
            </button>
          ))}
        </div>
      </div>

      {resultats.length > 0 ? (
        <TableauEleves
          eleves={resultats}
          groupeParId={groupeParId}
          onVoir={ouvrir}
          onMessage={ecrire}
        />
      ) : (
        <div className="eleves__vide">
          <EtatVide
            titre="No student here"
            texte="Nobody matches this name and group. Clear the filters to see the whole class."
            icone="students"
            action={{ libelle: 'Clear filters', executer: reinitialiser }}
          />
        </div>
      )}

      {selection &&
        createPortal(
          <div
            className="tiroir-voile voile-entree"
            onMouseDown={evenement => {
              if (evenement.target === evenement.currentTarget) fermer()
            }}
          >
            <aside
              className="tiroir tiroir-entree"
              ref={panneau}
              role="dialog"
              aria-modal="true"
              aria-labelledby="titre-tiroir-eleve"
              tabIndex={-1}
            >
              <header className="tiroir__entete">
                <span className="tiroir__surtitre">Student</span>
                <button className="tiroir__fermer" type="button" onClick={fermer} aria-label="Close student">
                  <Icone nom="close" taille={18} />
                </button>
              </header>

              <div className="tiroir__profil">
                <Avatar src={selection.avatar} nom={`${selection.prenom} ${selection.nom}`} taille={68} />
                <h2 id="titre-tiroir-eleve">
                  {selection.prenom} {selection.nom}
                </h2>
                <p className="tiroir__email">{selection.email}</p>
                {groupeParId(selection.groupeId) && (
                  <Pastille teinte="sarcelle">
                    {groupeParId(selection.groupeId)?.code} · {groupeParId(selection.groupeId)?.cours}
                  </Pastille>
                )}
              </div>

              <div className="tiroir__jauge">
                <div className="tiroir__jauge-entete">
                  <span>Attendance</span>
                  <strong>{selection.assiduite}%</strong>
                </div>
                <span className="jauge tiroir__jauge-barre">
                  <span
                    className={['jauge__remplie', selection.assiduite < 80 && 'jauge__remplie--alerte']
                      .filter(Boolean)
                      .join(' ')}
                    style={{ width: `${selection.assiduite}%` }}
                  />
                </span>
              </div>

              <dl className="tiroir__details">
                <div>
                  <dt>Last active</dt>
                  <dd>{selection.derniereActivite}</dd>
                </div>
                <div>
                  <dt>Status</dt>
                  <dd>
                    {selection.statut === 'actif'
                      ? 'Active'
                      : selection.statut === 'absent'
                        ? 'Absent'
                        : 'Running late'}
                  </dd>
                </div>
              </dl>

              <div className="tiroir__actions">
                <Bouton onClick={() => ecrire(selection)} iconeGauche={<Icone nom="messages" taille={16} />}>
                  Message
                </Bouton>
                {groupeParId(selection.groupeId) && (
                  <LienBouton
                    to={`/groups/${selection.groupeId}`}
                    variante="fantome"
                    onClick={fermer}
                  >
                    Open group
                  </LienBouton>
                )}
              </div>

              <p className="tiroir__note">
                Demo profile — attendance and activity are sample data, not a live record.
              </p>
            </aside>
          </div>,
          document.body,
        )}
    </section>
  )
}
